-- Concern updates: students can read their timeline; assigned staff can create/update their work; admins can manage all.
-- Validate that timeline updates can only be written for a concern the caller
-- is authorized to update. This prevents a staff account from moving an update
-- onto another concern by changing concern_id in a client request.
create or replace function public.validate_concern_update_actor()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if public.current_role() = 'staff' then
    if new.user_id <> auth.uid() or not exists (
      select 1 from public.assignments a
      where a.concern_id = new.concern_id and a.staff_id = auth.uid() and a.assignment_status = 'active'
    ) then
      raise exception 'Staff may update only actively assigned concerns';
    end if;
  elsif public.current_role() = 'student' then
    if new.user_id <> auth.uid() or new.update_type <> 'Concern Submitted' or not exists (
      select 1 from public.concerns c where c.concern_id = new.concern_id and c.student_id = auth.uid()
    ) then
      raise exception 'Students may only create their own submission update';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_concern_update_actor on public.concern_updates;
create trigger trg_validate_concern_update_actor before insert or update on public.concern_updates
for each row execute function public.validate_concern_update_actor();

