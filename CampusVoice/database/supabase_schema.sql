create table if not exists public.departments (
  department_id bigint generated by default as identity primary key,
  department_name text not null unique,
  department_type public.department_type not null default 'college',
  description text,
  status public.account_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  student_id text unique,
  staff_id text unique,
  admin_id text unique,
  first_name text not null,
  middle_initial text,
  last_name text not null,
  email text not null unique,
  role public.app_role not null default 'student',
  department_id bigint references public.departments(department_id),
  position text,
  coverage text,
  contact_number text,
  profile_picture text,
  account_status public.account_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_student_id_required check (role <> 'student' or student_id is not null),
  constraint users_staff_id_required check (role <> 'staff' or staff_id is not null),
  constraint users_admin_id_required check (role not in ('admin','super_admin') or admin_id is not null)
);

create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  category_name text not null unique,
  description text,
  status public.account_status not null default 'active',
  created_by uuid references public.users(user_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A location is stored as one complete selectable location: Building + Floor + Area/Room.
create table if not exists public.locations (
  location_id bigint generated by default as identity primary key,
  building text not null,
  floor text not null,
  area text not null,
  status public.account_status not null default 'active',
  created_by uuid references public.users(user_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint locations_unique_path unique (building, floor, area)
);

create table if not exists public.priorities (
  priority_id bigint generated by default as identity primary key,
  priority_name text not null unique,
  description text,
  target_response_hours numeric(8,2),
  target_resolution_hours numeric(8,2),
  status public.account_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.statuses (
  status_id bigint generated by default as identity primary key,
  status_name text not null unique,
  description text,
  status_type text not null default 'open',
  created_at timestamptz not null default now(),
  constraint statuses_type_check check (status_type in ('open','blocked','resolved','closed','cancelled'))
);

