-- SECURITY: public signup is always a Student. Staff/Admin/Super Admin accounts
-- must be created by the authorized backend/admin workflow and then assigned their role.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (
    user_id, email, first_name, middle_initial, last_name, role, student_id
  )
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(new.raw_user_meta_data->>'first_name',''), 'New'),
    nullif(new.raw_user_meta_data->>'middle_initial',''),
    coalesce(nullif(new.raw_user_meta_data->>'last_name',''), 'User'),
    'student',
    nullif(new.raw_user_meta_data->>'student_id','')
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Prevent ordinary users from changing identity, role, IDs, department, position,
-- coverage, email, or account status. Student names remain editable; staff/admin
-- identity fields are administrator-controlled.
create or replace function public.protect_user_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_role public.app_role;
begin
  select role into caller_role from public.users where user_id = auth.uid();

  if auth.uid() = old.user_id and coalesce(caller_role::text,'') not in ('admin','super_admin') then
    new.user_id := old.user_id;
    new.email := old.email;
    new.role := old.role;
    new.student_id := old.student_id;
    new.staff_id := old.staff_id;
    new.admin_id := old.admin_id;
    new.department_id := old.department_id;
    new.position := old.position;
    new.coverage := old.coverage;
    new.account_status := old.account_status;
    if old.role <> 'student' then
      new.first_name := old.first_name;
      new.middle_initial := old.middle_initial;
      new.last_name := old.last_name;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_protect_user_fields on public.users;
create trigger trg_protect_user_fields before update on public.users
for each row execute function public.protect_user_fields();

-- Validate that student concerns are submitted by students and assignments are
-- made only to staff by administrators.
create or replace function public.validate_concern_owner()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1 from public.users u
    where u.user_id = new.student_id and u.role = 'student' and u.account_status = 'active'
  ) then
    raise exception 'Concern owner must be an active student account';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_concern_owner on public.concerns;
create trigger trg_validate_concern_owner before insert or update on public.concerns
for each row execute function public.validate_concern_owner();

-- Students may submit the concern details, but priority and workflow status are
-- administrator-controlled. A student-created concern always starts as Submitted
-- with no priority; an administrator assigns the priority during review.
create or replace function public.enforce_student_concern_controls()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  submitted_id bigint;
begin
  select status_id into submitted_id from public.statuses where status_name = 'Submitted' limit 1;
  if public.current_role() = 'student' then
    if tg_op = 'INSERT' then
      new.priority_id := null;
      new.status_id := submitted_id;
    end if;
    if not exists (select 1 from public.categories where category_id = new.category_id and status = 'active') then
      raise exception 'Selected category is inactive or unavailable';
    end if;
    if not exists (select 1 from public.locations where location_id = new.location_id and status = 'active') then
      raise exception 'Selected location is inactive or unavailable';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_enforce_student_concern_controls on public.concerns;
create trigger trg_enforce_student_concern_controls before insert or update on public.concerns
for each row execute function public.enforce_student_concern_controls();

