-- Drop previous policies so this file can be safely rerun during setup.
do $$
declare r record;
begin
  for r in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('departments','users','categories','locations','priorities','statuses','concerns','assignments','concern_updates','photos','notifications','feedback','activity_logs','working_hours','holidays','system_settings')
  loop
