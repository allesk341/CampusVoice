create or replace function public.notify_staff_on_assignment()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  code text;
begin
  if tg_op = 'INSERT' then
    if new.assignment_status = 'active' then
      select concern_code into code from public.concerns where concern_id = new.concern_id;
      insert into public.notifications(user_id, concern_id, title, message)
      values (new.staff_id, new.concern_id, 'New Assignment', coalesce(code,'Concern') || ' has been assigned to you.');
    end if;
  elsif new.assignment_status = 'active' and (old.staff_id is distinct from new.staff_id or old.assignment_status is distinct from new.assignment_status) then
    select concern_code into code from public.concerns where concern_id = new.concern_id;
    insert into public.notifications(user_id, concern_id, title, message)
    values (new.staff_id, new.concern_id, 'New Assignment', coalesce(code,'Concern') || ' has been assigned to you.');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_notify_staff_on_assignment on public.assignments;
create trigger trg_notify_staff_on_assignment after insert or update on public.assignments
for each row execute function public.notify_staff_on_assignment();

create or replace function public.notify_student_on_concern_update()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  student_user uuid;
  code text;
  status_label text;
begin
  select c.student_id,c.concern_code into student_user,code from public.concerns c where c.concern_id = new.concern_id;
  select status_name into status_label from public.statuses where status_id = new.status_id;
  if student_user is not null and new.user_id <> student_user then
    insert into public.notifications(user_id, concern_id, title, message)
    values (student_user, new.concern_id, coalesce(status_label,'Concern Updated'),
            coalesce(code,'Concern') || ' was updated to ' || coalesce(status_label,new.update_type) || '.');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_notify_student_on_concern_update on public.concern_updates;
create trigger trg_notify_student_on_concern_update after insert on public.concern_updates
for each row execute function public.notify_student_on_concern_update();

