-- Keep concern resolution timestamps consistent with status changes.
create or replace function public.sync_concern_resolution_times()
returns trigger
language plpgsql
as $$
declare
  s text;
begin
  select status_name into s from public.statuses where status_id = new.status_id;
  if s = 'Resolved' and old.status_id is distinct from new.status_id then
    new.resolved_at := coalesce(new.resolved_at, now());
  elsif s <> 'Resolved' and s <> 'Closed' then
    new.resolved_at := null;
    new.closed_at := null;
  end if;
  if s = 'Closed' and old.status_id is distinct from new.status_id then
    new.closed_at := coalesce(new.closed_at, now());
    new.resolved_at := coalesce(new.resolved_at, now());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_sync_concern_resolution_times on public.concerns;
create trigger trg_sync_concern_resolution_times before update on public.concerns
for each row execute function public.sync_concern_resolution_times();

