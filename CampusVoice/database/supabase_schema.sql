  bucket_id = 'campusvoice-files' and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.current_role() in ('admin','super_admin')
    or exists (
      select 1 from public.assignments a
      join public.concerns c on c.concern_id = a.concern_id
      where a.staff_id = auth.uid()
        and a.assignment_status = 'active'
        and (storage.foldername(name))[1] = c.student_id::text
        and (storage.foldername(name))[2] = 'concerns'
        and (storage.foldername(name))[3] = c.concern_id::text
    )
  )
);

